def plain_vertex(name, number, x, y):
    return node(name, str(number), x, y)


def gap(name, x, y):
    return node(name, r"$\cdots$", x, y, r"font=\normalsize,inner sep=2pt")


def chain(body, names):
    return body + "".join(edge(a, b) for a, b in zip(names, names[1:]))


