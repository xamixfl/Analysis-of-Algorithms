def iterative_trace(number):
    nodes = ["I0", "I1"]
    edges = []
    n_source, a_source = "I0", "I1"
    k = 0
    while number:
        for operator in (2, 3, 4, 5, 6):
            nodes.append(f"I{operator}_{k}")
        edges += [(n_source, f"I{operator}_{k}") for operator in (2, 3, 4)]
        edges += [(f"I3_{k}", f"I5_{k}"), (f"I4_{k}", f"I6_{k}"),
                  (a_source, f"I5_{k}")]
        number //= 10
        n_source, a_source = f"I6_{k}", f"I5_{k}"
        k += 1
    nodes += [f"I2_{k}", "I7"]
    edges += [(n_source, f"I2_{k}"), (a_source, "I7")]
    return nodes, edges


def recursive_trace(number, depth=0):
    key = lambda operator: f"R{operator}_{depth}"
    nodes = [key(0), key(1)]
    edges = [(key(0), key(1))]
    if number == 0:
        return nodes + [key(2)], edges + [(key(0), key(2))], key(2)
    nodes += [key(operator) for operator in (3, 4, 5, "6a", "6b", 7)]
    edges += [(key(0), key(3)), (key(0), key(4)), (key(0), key(5)),
              (key(3), key(5)), (key(4), key("6a")), (key(5), key("6a")),
              (key("6a"), f"R0_{depth+1}")]
    child_nodes, child_edges, child_result = recursive_trace(number // 10, depth + 1)
    nodes += child_nodes
    edges += child_edges + [(child_result, key("6b")), (key("6b"), key(7))]
    return nodes, edges, key(7)


