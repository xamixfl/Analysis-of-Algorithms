def save(name, body):
    graph = not name.startswith("flow_")
    style = (
        "\\begin{tikzpicture}[x=1cm,y=1cm,>={Latex[length=2.2mm,width=1.5mm]},\n"
        " every node/.style={font=\\small,text=black},\n"
        " v/.style={draw=black,circle,line width=0.5pt,minimum size=11mm,inner sep=0pt,fill=white,font=\\normalsize},\n"
        " edge/.style={->,draw=black,line width=0.5pt},\n"
        " tag/.style={font=\\footnotesize,fill=white,inner sep=1.5pt}]\n"
        if graph else
        "\\begin{tikzpicture}[x=1cm,y=1cm,>=Stealth,\n"
        " every node/.style={font=\\small},\n"
        " v/.style={draw,circle,minimum size=8mm,inner sep=1pt,fill=white},\n"
        " edge/.style={->,line width=0.45pt},\n"
        " tag/.style={font=\\footnotesize,fill=white,inner sep=1pt}]\n"
    )
    (FIG / f"{name}.tex").write_text(
        "% Generated by generate_figures.py; vector TikZ, no raster images.\n"
        + style
        + body + "\n\\end{tikzpicture}\n", encoding="utf-8")


def node(name, label, x, y, style="v"):
    if style == "v":
        match = re.fullmatch(
            r"\$([IR])_(?:\{([^}]+)\}|(\d+))(?:\^\{\(\d+\)\})?\$", label
        )
        if match:
            operator = match.group(2) or match.group(3)
            label = RECURSIVE_NUMBERS[operator] if match.group(1) == "R" else operator
    return rf"\node[{style}] ({name}) at ({x},{y}) {{{label}}};" + "\n"


def edge(a, b, label="", opts=""):
    lab = rf" node[tag,auto] {{{label}}}" if label else ""
    return rf"\draw[edge] ({a}) to[{opts}]{lab} ({b});" + "\n"


